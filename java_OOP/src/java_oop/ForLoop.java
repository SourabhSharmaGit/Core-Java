package java_oop;

public class ForLoop {

	
	
	public static void main(String[] args) {
		
		//Printing even numbers using for loop
		
		  for(int i=2; i<=20; i = i+2) {
		  
		  System.out.println(i);
		  
		  
		  }
		 
		
		// table of 7
		
		for (int i=1; i<=10; i++) {
			System.out.println("7 x "+i +" = " + i*7 );
		}
		
	}
}
